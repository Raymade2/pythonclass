import { NextRequest, NextResponse } from "next/server";
import { getCurrentUser } from "@/lib/auth";
import * as finance from "@/lib/repo/finance";
import * as academics from "@/lib/repo/academics";
import * as people from "@/lib/repo/people";
import { formatDate, daysOverdue } from "@/lib/format";

function csvEscape(v: unknown): string {
  const s = v === null || v === undefined ? "" : String(v);
  if (/[",\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

function toCsv(columns: string[], rows: (string | number | null)[][]): string {
  const head = columns.map(csvEscape).join(",");
  const body = rows.map((r) => r.map(csvEscape).join(",")).join("\r\n");
  return `\uFEFF${head}\r\n${body}`;
}

export async function GET(req: NextRequest) {
  const user = await getCurrentUser();
  if (!user || !["SUPER_ADMIN", "ADMIN"].includes(user.role)) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const sp = req.nextUrl.searchParams;
  const type = sp.get("type") ?? "";
  const sessionId = Number(sp.get("session")) || 0;
  const termId = Number(sp.get("term")) || 0;
  const classId = Number(sp.get("class")) || 0;
  const groupId = Number(sp.get("group")) || 0;
  const q = sp.get("q") ?? "";
  const status = sp.get("status") ?? "";
  const method = sp.get("method") ?? "";
  const from = sp.get("from") ?? "";
  const to = sp.get("to") ?? "";
  const dueBefore = sp.get("dueBefore") ?? "";
  const minOutstanding = sp.get("minOutstanding") ?? "";
  const granularity = sp.get("granularity") ?? "monthly";

  let columns: string[] = [];
  let rows: (string | number | null)[][] = [];
  let filename = "export.csv";

  const current = academics.getCurrentAcademic();
  const effSessionId = sessionId || current?.session.id || 0;
  const session = academics.getSessionById(effSessionId);
  const terms = session ? academics.listTermsForSession(session.id) : [];
  const effTermId = termId || terms.find((t) => t.isCurrent)?.id || terms[0]?.id || 0;

  if (type === "debtors") {
    filename = `sfgs-debtors-${new Date().toISOString().slice(0, 10)}.csv`;
    const result = finance.debtorRows(
      { q: q || undefined, sessionId: effSessionId, termId: effTermId, classId: classId || undefined, classGroupId: groupId || undefined },
      0
    );
    columns = ["Student", "Student ID", "Admission No", "Class", "Parent/Guardian", "Phone", "Total Bill (NGN)", "Total Paid (NGN)", "Outstanding (NGN)", "Due Date", "Days Overdue", "Status"];
    rows = result.rows
      .filter((d) => (!dueBefore || (d.dueDate && new Date(d.dueDate) <= new Date(dueBefore))) && (!minOutstanding || d.outstanding >= Number(minOutstanding)))
      .map((d) => [
        `${d.firstName} ${d.middleName ?? ""} ${d.lastName}`.trim(),
        d.studentCode,
        d.admissionNumber,
        d.className ?? "",
        d.parentName ?? "",
        d.parentPhone ?? "",
        d.totalBill,
        d.totalPaid,
        d.outstanding,
        d.dueDate ? formatDate(d.dueDate) : "",
        daysOverdue(d.dueDate),
        daysOverdue(d.dueDate) > 0 ? "OVERDUE" : "PARTIALLY PAID",
      ]);
  } else if (type === "payments") {
    filename = `sfgs-payments-${new Date().toISOString().slice(0, 10)}.csv`;
    const result = finance.listAllPayments({
      q: q || undefined,
      sessionId: sessionId || undefined,
      termId: termId || undefined,
      classId: classId || undefined,
      method: method || undefined,
      status: status || undefined,
      from: from || undefined,
      to: to || undefined,
    });
    columns = ["Payment Reference", "Receipt No", "Student", "Student ID", "Class", "Invoice", "Payment Type", "Amount (NGN)", "Method", "Channel", "Date", "Recorded By", "Status"];
    rows = result.map((p) => [
      p.reference,
      p.receiptNumber ?? "",
      `${p.firstName} ${p.lastName}`,
      p.studentCode,
      p.className ?? "",
      p.invoiceNumber ?? "",
      "School Fee Payment",
      p.amount,
      p.method,
      p.channel ?? "",
      formatDate(p.paymentDate),
      p.recordedByName ?? "",
      p.status,
    ]);
  } else if (type === "invoices") {
    filename = `sfgs-invoices-${new Date().toISOString().slice(0, 10)}.csv`;
    const result = finance.listAllInvoices({
      q: q || undefined,
      sessionId: effSessionId,
      termId: effTermId,
      classId: classId || undefined,
      status: status || undefined,
    });
    columns = ["Invoice Number", "Student", "Student ID", "Class", "Session", "Term", "Total (NGN)", "Paid (NGN)", "Balance (NGN)", "Due Date", "Status", "Generated By", "Created"];
    rows = result.map((i) => [
      i.invoiceNumber,
      `${i.firstName} ${i.middleName ?? ""} ${i.lastName}`.trim(),
      i.studentCode,
      i.className ?? "",
      i.sessionName,
      i.termName,
      i.totalAmount,
      i.amountPaid,
      i.balance,
      i.dueDate ? formatDate(i.dueDate) : "",
      i.status,
      i.generatedByName ?? "",
      formatDate(i.createdAt),
    ]);
  } else if (type === "students") {
    filename = `sfgs-students-${new Date().toISOString().slice(0, 10)}.csv`;
    const result = people.listStudents({
      q: q || undefined,
      classId: classId || undefined,
      sessionId: effSessionId,
      termId: effTermId,
      status: status || undefined,
      limit: 5000,
    });
    columns = ["Student", "Student ID", "Admission No", "Class", "Gender", "Date of Birth", "Parent/Guardian", "Phone", "Admission Date", "Status"];
    rows = result.rows.map((s) => [
      `${s.firstName} ${s.middleName ?? ""} ${s.lastName}`.trim(),
      s.studentCode,
      s.admissionNumber,
      s.className ?? "",
      s.gender,
      s.dateOfBirth ? formatDate(s.dateOfBirth) : "",
      s.parentName ?? "",
      s.parentPhone ?? "",
      formatDate(s.admissionDate),
      s.status,
    ]);
  } else if (type === "classes") {
    filename = `sfgs-class-performance-${new Date().toISOString().slice(0, 10)}.csv`;
    const perf = finance.classPerformance(effSessionId, effTermId, { classId: classId || undefined });
    columns = ["Class", "Group", "Students", "Expected (NGN)", "Paid (NGN)", "Outstanding (NGN)", "Payment %"];
    rows = perf.map((p) => [
      p.className,
      p.groupName ?? "",
      p.studentCount,
      p.expected,
      p.paid,
      p.outstanding,
      p.expected > 0 ? Math.round((p.paid / p.expected) * 100) : 0,
    ]);
  } else if (type === "collection") {
    filename = `sfgs-collection-${granularity}-${new Date().toISOString().slice(0, 10)}.csv`;
    const defaultFrom = from || new Date(Date.now() - 180 * 86400000).toISOString().slice(0, 10);
    const defaultTo = to || new Date().toISOString().slice(0, 10);
    const daily = finance.dailyPaymentTotals(defaultFrom, defaultTo, {
      sessionId: effSessionId || undefined,
      termId: effTermId || undefined,
      classId: classId || undefined,
    });
    const key = (day: string) => {
      const d = new Date(day + "T00:00:00");
      if (granularity === "daily") return day;
      if (granularity === "annual") return String(d.getFullYear());
      if (granularity === "weekly") {
        const monday = new Date(d);
        monday.setDate(d.getDate() - ((d.getDay() + 6) % 7));
        return `Week of ${monday.toLocaleDateString("en-GB")}`;
      }
      if (granularity === "termly") return session?.name ?? "Term";
      return d.toLocaleDateString("en-GB", { month: "long", year: "numeric" });
    };
    const agg = new Map<string, { total: number; days: number }>();
    for (const d of daily) {
      const k = key(d.day);
      const cur = agg.get(k) ?? { total: 0, days: 0 };
      cur.total += d.total;
      cur.days += 1;
      agg.set(k, cur);
    }
    columns = ["Period", "Active Days", "Amount Collected (NGN)"];
    rows = [...agg.entries()].map(([k, v]) => [k, v.days, v.total]);
  } else {
    return NextResponse.json({ error: "Unknown export type" }, { status: 400 });
  }

  const csv = toCsv(columns, rows);
  return new NextResponse(csv, {
    headers: {
      "Content-Type": "text/csv; charset=utf-8",
      "Content-Disposition": `attachment; filename="${filename}"`,
      "Cache-Control": "no-store",
    },
  });
}
